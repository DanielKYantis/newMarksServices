const CONVERSION_MARKER = '.bootstrapmade-php-conversion';

function fail(string $message, int $code = 1): never
{
    fwrite(STDERR, "Error: {$message}\n");
    exit($code);
}

function usage(): never
{
    $script = basename(__FILE__);
    fwrite(STDERR, <<<TEXT
Usage:
  php scripts/{$script} --source=/path/to/export --output=/path/to/php-site [--assets-from=/path/to/existing/assets] [--layout=index.html] [--force]

Options:
  --source   BootstrapMade export directory containing HTML pages.
  --output   New directory for the converted PHP site. It must differ from source.
  --assets-from  Existing assets directory to preserve before exported assets are layered over it.
  --layout   Page used as the shared header/nav/footer template (default: index.html).
  --force    Replace a prior output created by this converter.

TEXT);
    exit(2);
}

function canonicalPath(string $path): string
{
    $resolved = realpath($path);
    return $resolved !== false ? rtrim($resolved, DIRECTORY_SEPARATOR) : rtrim($path, DIRECTORY_SEPARATOR);
}

function removeDirectory(string $directory): void
{
    $iterator = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($directory, FilesystemIterator::SKIP_DOTS),
        RecursiveIteratorIterator::CHILD_FIRST
    );

    foreach ($iterator as $item) {
        $path = $item->getPathname();
        $item->isDir() ? rmdir($path) : unlink($path);
    }

    rmdir($directory);
}

function prepareOutput(string $source, string $output, bool $force): void
{
    if (canonicalPath($source) === canonicalPath($output)) {
        fail('Source and output must be different directories. In-place conversion is intentionally disabled.');
    }

    if (is_dir($output)) {
        $marker = $output . DIRECTORY_SEPARATOR . CONVERSION_MARKER;
        if (!$force) {
            fail("Output already exists: {$output}. Use --force only for a prior converter output.");
        }
        if (!is_file($marker)) {
            fail("Refusing to replace an unrecognized directory: {$output}");
        }
        removeDirectory($output);
    } elseif (file_exists($output)) {
        fail("Output exists and is not a directory: {$output}");
    }

    if (!mkdir($output, 0775, true) && !is_dir($output)) {
        fail("Unable to create output directory: {$output}");
    }

    file_put_contents($output . DIRECTORY_SEPARATOR . CONVERSION_MARKER, "Generated by " . basename(__FILE__) . "\n");
}

function copyExportAssets(string $source, string $output): void
{
    $iterator = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($source, FilesystemIterator::SKIP_DOTS),
        RecursiveIteratorIterator::SELF_FIRST
    );

    foreach ($iterator as $item) {
        $relative = substr($item->getPathname(), strlen($source) + 1);
        if (
            $item->getFilename() === '.DS_Store'
            || strcasecmp($item->getFilename(), 'Readme.txt') === 0
            || preg_match('/\.html?$/i', $relative)
        ) {
            continue;
        }

        $destination = $output . DIRECTORY_SEPARATOR . $relative;
        if ($item->isDir()) {
            if (!is_dir($destination) && !mkdir($destination, 0775, true) && !is_dir($destination)) {
                fail("Unable to create directory: {$destination}");
            }
            continue;
        }

        $parent = dirname($destination);
        if (!is_dir($parent) && !mkdir($parent, 0775, true) && !is_dir($parent)) {
            fail("Unable to create directory: {$parent}");
        }
        if (!copy($item->getPathname(), $destination)) {
            fail("Unable to copy: {$relative}");
        }
    }
}

function copyPreservedAssets(string $source, string $destination): void
{
    if (!is_dir($destination) && !mkdir($destination, 0775, true) && !is_dir($destination)) {
        fail("Unable to create preserved assets directory: {$destination}");
    }

    $iterator = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($source, FilesystemIterator::SKIP_DOTS),
        RecursiveIteratorIterator::SELF_FIRST
    );

    foreach ($iterator as $item) {
        if ($item->getFilename() === '.DS_Store') {
            continue;
        }

        $relative = substr($item->getPathname(), strlen($source) + 1);
        $target = $destination . DIRECTORY_SEPARATOR . $relative;
        if ($item->isDir()) {
            if (!is_dir($target) && !mkdir($target, 0775, true) && !is_dir($target)) {
                fail("Unable to create preserved asset directory: {$target}");
            }
            continue;
        }

        $parent = dirname($target);
        if (!is_dir($parent) && !mkdir($parent, 0775, true) && !is_dir($parent)) {
            fail("Unable to create preserved asset directory: {$parent}");
        }
        if (!copy($item->getPathname(), $target)) {
            fail("Unable to preserve asset: {$relative}");
        }
    }
}

function matchOne(string $pattern, string $html, string $label): array
{
    if (preg_match($pattern, $html, $matches, PREG_OFFSET_CAPTURE) !== 1) {
        fail("Could not find {$label}.");
    }
    return $matches;
}

function outerTag(string $html, string $tag, ?string $requiredAttribute = null): string
{
    $attribute = $requiredAttribute === null ? '' : '(?=[^>]*' . preg_quote($requiredAttribute, '~') . ')';
    $matches = matchOne("~<{$tag}\\b{$attribute}[^>]*>.*?</{$tag}>~is", $html, "<{$tag}> block");
    return $matches[0][0];
}

function innerTag(string $html, string $tag): string
{
    $matches = matchOne("~<{$tag}\\b[^>]*>(.*?)</{$tag}>~is", $html, "<{$tag}> block");
    return $matches[1][0];
}

function tagAttributes(string $html, string $tag): string
{
    $matches = matchOne("~<{$tag}\\b([^>]*)>~is", $html, "<{$tag}> opening tag");
    return $matches[1][0];
}

function attributeValue(string $attributes, string $name): string
{
    $quotedName = preg_quote($name, '~');
    if (preg_match("~\\b{$quotedName}\\s*=\\s*([\"'])(.*?)\\1~is", $attributes, $matches) === 1) {
        return html_entity_decode($matches[2], ENT_QUOTES | ENT_HTML5, 'UTF-8');
    }
    return '';
}

function metaContent(string $head, string $name): string
{
    if (preg_match_all('~<meta\\b[^>]*>~is', $head, $tags) !== false) {
        foreach ($tags[0] as $tag) {
            $attributes = tagAttributes($tag, 'meta');
            if (strcasecmp(attributeValue($attributes, 'name'), $name) === 0) {
                return attributeValue($attributes, 'content');
            }
        }
    }
    return '';
}

function titleContent(string $head): string
{
    if (preg_match('~<title\\b[^>]*>(.*?)</title>~is', $head, $matches) !== 1) {
        return '';
    }
    return html_entity_decode(trim(strip_tags($matches[1])), ENT_QUOTES | ENT_HTML5, 'UTF-8');
}

function customBlock(string $html, string $kind): string
{
    $kindQuoted = preg_quote($kind, '~');
    $pattern = "~<!--\\s*[^>]*Custom {$kindQuoted} Code\\s*-->(.*?)(?=<!--|$)~is";
    return preg_match($pattern, $html, $matches) === 1 ? trim($matches[1]) : '';
}

function withoutCustomBlock(string $html, string $kind): string
{
    $kindQuoted = preg_quote($kind, '~');
    return preg_replace("~\\s*<!--\\s*[^>]*Custom {$kindQuoted} Code\\s*-->.*?(?=\\s*<!--|$)~is", '', $html, 1) ?? $html;
}

function replaceHtmlLinks(string $html): string
{
    $html = preg_replace_callback(
        "~(href\\s*=\\s*[\"'])([^\"'?#]+)\\.html((?:[?#][^\"']*)?)([\"'])~i",
        static fn(array $m): string => $m[1] . $m[2] . '.php' . $m[3] . $m[4],
        $html
    ) ?? $html;

    return replaceStockImagePaths($html);
}

