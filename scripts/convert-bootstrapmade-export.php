                    "~class=([\"'])(.*?)\\1~is",
                    'class=$1$2 <?= is_active($pageKey, ' . phpLiteral($target) . ') ?>$1',
                    $attributes,
                    1
                ) ?? $attributes;
            } else {
                $attributes .= ' class="<?= is_active($pageKey, ' . phpLiteral($target) . ') ?>"';
            }
            return '<a' . $attributes . '>';
        },
        $nav
    ) ?? $nav;
}

