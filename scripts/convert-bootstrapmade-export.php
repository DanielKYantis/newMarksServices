            $before = $m[1];
            $after = $m[5];
            $target = basename(parse_url($m[3], PHP_URL_PATH) ?: $m[3]);
            $attributes = $before . 'href=' . $m[2] . $m[3] . $m[4] . $m[2] . $after;
            if (preg_match("~class=([\"'])(.*?)\\1~is", $attributes) === 1) {
